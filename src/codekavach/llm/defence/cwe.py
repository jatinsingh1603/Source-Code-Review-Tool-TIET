def filter_cwes(proposed: tuple[int, ...], *, trusted: tuple[int, ...] = ()) -> tuple[int, ...]:
    """The numbers of ``proposed`` that are on the allow-list or among ``trusted``, in order."""
    seen: list[int] = []
    for number in proposed:
        if (number in ALLOWED_CWES or number in trusted) and number not in seen:
            seen.append(number)
    return tuple(seen)
