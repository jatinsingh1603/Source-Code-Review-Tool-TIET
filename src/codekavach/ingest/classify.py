"""Binary, minified, generated and vendored detection (E06-01).

Owning epic: E06.

Each function is pure and takes only what it needs, so the rule each one implements is testable
in isolation against a table of positive and negative cases. ``is_generated`` and ``is_vendored``
drive real privacy decisions downstream: a vendored file is third-party code a provider can look
up in a public corpus (re-identification, ``docs/research/INSIGHTS.md`` section 4.2), and the
slicer (E11) is required to honour both flags.
"""

import re

# A file is binary if a NUL byte appears anywhere in its first BINARY_SNIFF_BYTES.
BINARY_SNIFF_BYTES = 8192

_MINIFIED_NAME = re.compile(r"(\.min\.(js|css)|-min\.js)$", re.IGNORECASE)
_MINIFIED_LINE_LENGTH = 500
_MINIFIED_LINE_SAMPLE = 200
_MINIFIED_SEMICOLON_RATIO = 5

_GENERATED_MARKERS = ("@generated", "Code generated by", "DO NOT EDIT", "Autogenerated")
_GENERATED_LINE_SAMPLE = 5
_GENERATED_PATH_PATTERNS = (
    re.compile(r"_pb2\.py$"),
    re.compile(r"\.pb\.go$"),
    re.compile(r"\.g\.dart$"),
    re.compile(r"_generated\.[^/]+$"),
    re.compile(r"(^|/)migrations/"),
)

_VENDORED_SEGMENTS = frozenset(
    {"vendor", "third_party", "node_modules", "Godeps", ".venv", "site-packages"}
)


def is_binary(head: bytes) -> bool:
    """True when a NUL byte appears in the first ``BINARY_SNIFF_BYTES`` of a file."""
    return b"\x00" in head[:BINARY_SNIFF_BYTES]


def is_minified(path: str, text: str, line_count: int) -> bool:
    """True when ``path`` or ``text`` matches one of the three minified-file rules.

    A file is minified when: its name matches ``*.min.js``, ``*.min.css`` or ``*-min.js``; or
    the median length of its first 200 lines exceeds 500 characters; or its ratio of semicolons
    to newlines exceeds 5 (a single-line, semicolon-heavy bundle with no literal newlines yet
    many statements).
    """
    if _MINIFIED_NAME.search(path):
        return True
    lines = text.split("\n")[:_MINIFIED_LINE_SAMPLE]
    if lines:
        lengths = sorted(len(line) for line in lines)
        median = lengths[len(lengths) // 2]
        if median > _MINIFIED_LINE_LENGTH:
            return True
    if line_count > 0:
        semicolons = text.count(";")
        if semicolons / line_count > _MINIFIED_SEMICOLON_RATIO:
            return True
    return False


def is_generated(path: str, head_text: str) -> bool:
    """True when the first 5 lines carry a generated-file marker, or the path matches one."""
    first_lines = head_text.split("\n")[:_GENERATED_LINE_SAMPLE]
    for line in first_lines:
        if any(marker in line for marker in _GENERATED_MARKERS):
            return True
    return any(pattern.search(path) for pattern in _GENERATED_PATH_PATTERNS)


def is_vendored(path: str) -> bool:
    """True when ``path`` contains a known third-party-code directory segment."""
    return any(segment in _VENDORED_SEGMENTS for segment in path.split("/"))
