"""Mining business vocabulary from a repository, as a suggestion (E08-04).

Owning epic: E08.

A client lists their business terms in ``privacy.domain_terms`` and the term detector redacts them
(E08-03). A repository holds more such terms than anyone lists: ``accrual``, ``mandate``,
``nach``. :func:`mine_domain_terms` finds candidates by comparing how often each sub-word of an
identifier or a string occurs in the repository with how often it occurs in general code. The
score is ``log(repository_rate / baseline_rate)``: a word that is rare in general code and common
here scores high (``accrual``), and a word that is common everywhere scores near zero (``value``).

**This is a suggestion path, never a rule.** Nothing is redacted from a mined term until a person
copies it into ``privacy.domain_terms``. The reasons are privacy reasons: a list that is wrong in
the aggressive direction redacts half the identifiers and the reviewing model can no longer reason,
and a list mined from the repository is itself a summary of the client's vocabulary, so writing
it somewhere that may be committed is a disclosure. The caller (the ``privacy terms suggest``
command) writes the result to the state directory only. A :class:`MinedTerm` holds a client word,
so it is classified ``RAW``, is never logged, and its ``repr`` is the default model one.

**Exclusions.** The caller passes ``excluded``: the keywords and builtins of the languages
(``LanguageSpec``), the public allowlist (E09-02) and the terms already configured. A word such as
``request`` is part of the names the design keeps in clear, and suggesting it would work against
that.

**The baseline** is a bundled table of sub-word rates (``data/term_baseline.tsv``) generated by
``tools/gen_term_baseline.py`` from permissively licensed public code; its header records the
source, the date and the licence. A word that is not in the table is given the table's floor rate,
the rate of a word seen about once. The table is sorted and holds no word shorter than four
characters.
"""

import importlib.resources
import math
from collections import Counter, defaultdict
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from functools import cache
from typing import ClassVar, Final

from codekavach.core.models import DataClassification, KavachModel
from codekavach.parsing.models import LiteralSpan
from codekavach.parsing.subtokens import split_subtokens
from codekavach.parsing.symbols import SymbolTable

DATA_PACKAGE: Final = "codekavach.privacy.detect.data"
BASELINE_FILE: Final = "term_baseline.tsv"
MIN_TERM_LENGTH: Final = 4
MIN_WORD_LENGTH: Final = 2  # the generator counts the same words in the denominator
DEFAULT_MIN_SCORE: Final = 4.0
DEFAULT_MIN_OCCURRENCES: Final = 2
DEFAULT_LIMIT: Final = 200
KINDS_SHOWN: Final = 3


class BaselineError(ValueError):
    """The bundled baseline table is malformed. This is a build defect, never a client input."""


@dataclass(frozen=True, slots=True)
class Baseline:
    """Rates of sub-words in general code: ``rates[word]`` is occurrences over ``total``."""

    rates: Mapping[str, float]
    floor_rate: float
    source: str

    def rate(self, word: str) -> float:
        """The general-code rate of ``word``, or the floor rate when the table has no entry."""
        return self.rates.get(word, self.floor_rate)


class MinedTerm(KavachModel):
    """One suggested term: the word, its score, how often it occurs and where."""

    DATA_CLASSIFICATION: ClassVar[DataClassification] = DataClassification.RAW

    term: str
    score: float
    occurrences: int
    sample_kinds: tuple[str, ...]


def parse_baseline(text: str) -> Baseline:
    """Parse the table: ``# key: value`` header lines, then sorted ``word<TAB>rate`` lines.

    Raises:
        BaselineError: a line is malformed, the words are not sorted, a word is shorter than
            four characters, or the header lacks ``floor_rate``.
    """
    header: dict[str, str] = {}
    rates: dict[str, float] = {}
    previous = ""
    for number, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        if line.startswith("#"):
            key, _, text_value = line[1:].partition(":")
            header[key.strip()] = text_value.strip()
            continue
        word, separator, rate = line.partition("\t")
        try:
            value = float(rate)
        except ValueError:
            value = math.nan
        if not separator or math.isnan(value) or not value > 0:
            raise BaselineError(f"baseline line {number} is not 'word<TAB>rate'")
        if len(word) < MIN_TERM_LENGTH or word != word.lower() or word <= previous:
            raise BaselineError(f"baseline line {number} is short, not lower case or not sorted")
        rates[word] = value
        previous = word
    try:
        floor = float(header["floor_rate"])
    except (KeyError, ValueError):
        raise BaselineError("the baseline header has no usable floor_rate") from None
    if not floor > 0:
        raise BaselineError("the baseline floor_rate must be positive")
    return Baseline(rates=rates, floor_rate=floor, source=header.get("source", ""))


@cache
def bundled_baseline() -> Baseline:
    """The baseline shipped with CodeKavach."""
    text = (importlib.resources.files(DATA_PACKAGE) / BASELINE_FILE).read_text(encoding="utf-8")
    return parse_baseline(text)


def eligible_words(name: str) -> Iterable[str]:
    """The lower-case alphabetic sub-words of ``name`` that are long enough to be terms."""
    for piece in split_subtokens(name):
        word = piece.lower()
        if len(word) >= MIN_TERM_LENGTH and word.isalpha():
            yield word


def _all_words(name: str) -> int:
    return sum(
        1 for piece in split_subtokens(name) if len(piece) >= MIN_WORD_LENGTH and piece.isalpha()
    )


def mine_domain_terms(
    symbol_tables: Iterable[SymbolTable],
    literals: Iterable[LiteralSpan],
    *,
    baseline: Baseline,
    excluded: Callable[[str], bool] = lambda word: False,
    min_score: float = DEFAULT_MIN_SCORE,
    min_occurrences: int = DEFAULT_MIN_OCCURRENCES,
    limit: int = DEFAULT_LIMIT,
) -> tuple[MinedTerm, ...]:
    """Rank the sub-words of the repository's identifiers and strings by how domain-specific.

    ``score = log(repository_rate / baseline_rate)`` where the repository rate is the word's
    share of all alphabetic sub-words seen. A word is returned when its score is at least
    ``min_score``, it occurs at least ``min_occurrences`` times, it is at least four letters
    long, and ``excluded(word)`` is false. The result is ordered by score, then occurrences,
    then the word, and holds at most ``limit`` terms, so it is the same on every run.
    """
    counts: Counter[str] = Counter()
    kinds: defaultdict[str, Counter[str]] = defaultdict(Counter)
    total = 0
    for table in symbol_tables:
        for symbol in table.symbols:
            total += _all_words(symbol.name)
            for word in eligible_words(symbol.name):
                counts[word] += 1
                kinds[word][str(symbol.kind)] += 1
    for literal in literals:
        total += _all_words(literal.raw_text)
        for word in eligible_words(literal.raw_text):
            counts[word] += 1
            kinds[word][f"literal:{literal.kind}"] += 1
    if total == 0:
        return ()
    ranked: list[MinedTerm] = []
    for word, occurrences in counts.items():
        if occurrences < min_occurrences or excluded(word):
            continue
        score = round(math.log((occurrences / total) / baseline.rate(word)), 6)
        if score < min_score:
            continue
        common = sorted(kinds[word].items(), key=lambda item: (-item[1], item[0]))[:KINDS_SHOWN]
        ranked.append(
            MinedTerm(
                term=word,
                score=score,
                occurrences=occurrences,
                sample_kinds=tuple(kind for kind, _ in common),
            )
        )
    ranked.sort(key=lambda item: (-item.score, -item.occurrences, item.term))
    return tuple(ranked[: max(0, limit)])
