"""Generate ``fixtures/kavachbank/ground-truth/terms.txt`` from the ground-truth manifest (E13-01).

Usage: ``uv run python tools/gen_terms.py [--out PATH] [--check]``.

The terms file is what Demo 1 hands to ``privacy.domain_terms_file``: the planted secrets (resolved
from the manifest's ``value_ref`` names through ``tests/support/synthetic.py``, so each value lives
in one place) followed by ``business_domain_dictionary``, one term per line in the format that
``codekavach.config.domain_terms`` reads (E05-18). A hand-maintained copy would drift from the
manifest, and a stale file would let Demo 1 criterion 4 pass for the wrong reason, so ``--check``
renders in memory, compares with the file on disk and exits 1 with a diff when they differ (2 when
the file is missing). CI and pre-commit run it.

The output is deterministic and carries no timestamp. This is development tooling and is not
shipped in the package.
"""

import argparse
import difflib
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests.support.kavachbank import (  # noqa: E402 - the repository root must be importable first
    MANIFEST_PATH,
    TERMS_PATH,
    ManifestError,
    load_manifest,
    terms_for,
)

HEADER = (
    "# Generated by tools/gen_terms.py from ground-truth/manifest.yaml. Do not edit by hand.\n"
    "# Planted secrets first, then the business domain dictionary; one term per line.\n"
)
DIFF_LINES = 40


def render(manifest_path: Path = MANIFEST_PATH) -> str:
    """The text of the terms file for the manifest at ``manifest_path``."""
    return HEADER + "\n".join(terms_for(load_manifest(manifest_path))) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    """Write the terms file, or with ``--check`` compare it; returns the exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--out", type=Path, default=TERMS_PATH, help="the terms file to write")
    parser.add_argument("--manifest", type=Path, default=MANIFEST_PATH, help="the manifest to read")
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    args = parser.parse_args(argv)
    try:
        expected = render(args.manifest)
    except ManifestError as error:
        print(f"gen_terms: {error}", file=sys.stderr)
        return 2
    if not args.check:
        args.out.write_text(expected, encoding="utf-8", newline="\n")
        return 0
    if not args.out.exists():
        print(f"gen_terms: {args.out} is missing; run tools/gen_terms.py", file=sys.stderr)
        return 2
    actual = args.out.read_text(encoding="utf-8")
    if actual == expected:
        return 0
    diff = difflib.unified_diff(
        actual.splitlines(), expected.splitlines(), "on disk", "expected", lineterm=""
    )
    print("\n".join(list(diff)[:DIFF_LINES]), file=sys.stderr)
    print("gen_terms: the terms file is stale; run tools/gen_terms.py", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
