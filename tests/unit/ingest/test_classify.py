"""``is_binary``, ``is_minified``, ``is_generated``, ``is_vendored`` (E06-01)."""

import pytest

from codekavach.ingest.classify import is_binary, is_generated, is_minified, is_vendored

BINARY_CASES = [
    pytest.param(b"hello\x00world", True, id="nul-byte-present"),
    pytest.param(b"hello world", False, id="plain-text"),
    pytest.param(b"", False, id="empty"),
]


@pytest.mark.parametrize(("head", "expected"), BINARY_CASES)
def test_is_binary(head: bytes, expected: bool) -> None:
    assert is_binary(head) is expected


MINIFIED_CASES = [
    pytest.param("app.min.js", "var x=1;", 1, True, id="dot-min-js-name"),
    pytest.param("app.min.css", "body{color:red}", 1, True, id="dot-min-css-name"),
    pytest.param("app-min.js", "var x=1;", 1, True, id="dash-min-js-name"),
    pytest.param("app.js", "x" * 600, 1, True, id="long-median-line"),
    pytest.param("app.js", ";" * 50 + "\n", 1, True, id="high-semicolon-ratio"),
    pytest.param("app.js", "var x = 1;\nvar y = 2;\n", 2, False, id="ordinary-file"),
    pytest.param("README.md", "hello world\n", 1, False, id="not-minified-markdown"),
]


@pytest.mark.parametrize(("path", "text", "line_count", "expected"), MINIFIED_CASES)
def test_is_minified(path: str, text: str, line_count: int, expected: bool) -> None:
    assert is_minified(path, text, line_count) is expected


GENERATED_CASES = [
    pytest.param("a.py", "# @generated\nx = 1\n", True, id="at-generated-marker"),
    pytest.param(
        "a.go", "// Code generated by protoc. DO NOT EDIT.\n", True, id="code-generated-by"
    ),
    pytest.param("a.py", "# DO NOT EDIT\n", True, id="do-not-edit"),
    pytest.param("a.py", "# Autogenerated file\n", True, id="autogenerated"),
    pytest.param("models_pb2.py", "x = 1\n", True, id="pb2-path-pattern"),
    pytest.param("api.pb.go", "x = 1\n", True, id="pb-go-path-pattern"),
    pytest.param("widget.g.dart", "x = 1\n", True, id="g-dart-path-pattern"),
    pytest.param("schema_generated.py", "x = 1\n", True, id="generated-suffix-pattern"),
    pytest.param("migrations/0001_init.py", "x = 1\n", True, id="migrations-dir"),
    pytest.param(
        "a.py", "x = 1\n# not a marker beyond line 5\n" * 10, False, id="marker-past-line-5"
    ),
    pytest.param("a.py", "x = 1\n", False, id="ordinary-file"),
]


@pytest.mark.parametrize(("path", "head_text", "expected"), GENERATED_CASES)
def test_is_generated(path: str, head_text: str, expected: bool) -> None:
    assert is_generated(path, head_text) is expected


VENDORED_CASES = [
    pytest.param("vendor/lib.go", True, id="vendor-segment"),
    pytest.param("third_party/lib.cc", True, id="third-party-segment"),
    pytest.param("node_modules/pkg/index.js", True, id="node-modules-segment"),
    pytest.param("Godeps/_workspace/x.go", True, id="godeps-segment"),
    pytest.param(".venv/lib/x.py", True, id="venv-segment"),
    pytest.param("lib/site-packages/x.py", True, id="site-packages-segment"),
    pytest.param("src/app.py", False, id="ordinary-path"),
]


@pytest.mark.parametrize(("path", "expected"), VENDORED_CASES)
def test_is_vendored(path: str, expected: bool) -> None:
    assert is_vendored(path) is expected
